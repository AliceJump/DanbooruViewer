"""Fixed Unicode lowercase mapping shared by the index builder and Dart.

completion_lowercase.json pins Unicode 15.0.0 simple scalar lowercase, including
U+0130 -> U+0069. Runtime Python/Dart/JavaScript Unicode versions must not change
the persisted key contract. Regenerate the Dart constants with this module;
--check verifies the checked-in constants without writing files.
"""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(__file__).with_name("completion_lowercase.json")
DART_OUTPUT = ROOT / "lib" / "completion_case_mapping.dart"


def _load_mapping():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    version = data["unicodeVersion"]
    ranges = data["ranges"]
    if not isinstance(version, str) or not isinstance(ranges, list):
        raise ValueError("invalid completion lowercase mapping")
    previous_end = -1
    for row in ranges:
        if not isinstance(row, list) or len(row) != 4 or any(type(value) is not int for value in row):
            raise ValueError("invalid completion lowercase range")
        start, end, step, delta = row
        if not (previous_end < start <= end <= 0x10FFFF and step in (1, 2)):
            raise ValueError("unordered completion lowercase range")
        if not (0 <= start + delta <= end + delta <= 0x10FFFF):
            raise ValueError("invalid lowercase scalar")
        previous_end = end
    return version, ranges


UNICODE_VERSION, RANGES = _load_mapping()
_TRANSLATION = {
    scalar: scalar + delta
    for start, end, step, delta in RANGES
    for scalar in range(start, end + 1, step)
}


def normalize_completion_key(value: str) -> str:
    """Apply the fixed mapping without contextual or multi-scalar expansion."""
    return value.lower() if value.isascii() else value.translate(_TRANSLATION)


def render_dart() -> str:
    lines = [
        "// Generated by python scripts/completion_normalization.py; do not edit.",
        "// Canonical source: scripts/completion_lowercase.json.",
        f"const completionLowercaseUnicodeVersion = '{UNICODE_VERSION}';",
        "",
        "// Each range is (first scalar, last scalar, step, lowercase delta).",
        "const completionLowercaseRanges = <(int, int, int, int)>[",
        *[f"  ({start}, {end}, {step}, {delta})," for start, end, step, delta in RANGES],
        "];",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_dart()
    if args.check:
        if not DART_OUTPUT.is_file() or DART_OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Completion mapping is stale; run python scripts/completion_normalization.py")
        print(f"Completion Unicode {UNICODE_VERSION} mapping is current.")
    else:
        DART_OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Generated {len(RANGES)} completion lowercase ranges -> {DART_OUTPUT}")


if __name__ == "__main__":
    main()
